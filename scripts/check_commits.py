#!/usr/bin/env python3
"""Validate Conventional Commit subjects: <type>(<scope>): <description>.

usage: check_commits.py FILE [FILE...]   (one subject per line)
Merge commits ("Merge ...") and reverts generated by git ("Revert ...") are allowed.
"""

import re
import sys

TYPES = "feat|fix|refactor|docs|test|ci|build|chore|perf"
PATTERN = re.compile(rf"^({TYPES})(\([a-z0-9][a-z0-9-]*\))?!?: \S.{{0,99}}$")
ALLOWED_PREFIXES = ("Merge ", "Revert ")


def check(subject: str) -> bool:
    return subject.startswith(ALLOWED_PREFIXES) or bool(PATTERN.match(subject))


def main(paths: list[str]) -> int:
    bad = []
    for path in paths:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                subject = line.rstrip("\n")
                if subject and not check(subject):
                    bad.append(subject)
    if bad:
        print("Not Conventional Commits (<type>(<scope>): <description>, types: " + TYPES + "):")
        for s in bad:
            print(f"  - {s}")
        return 1
    print("all subjects follow Conventional Commits")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
